#!/usr/bin/env python3
"""Reproducible multinomial naive Bayes training, Python standard library only."""
import collections
import hashlib
import json
import math
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[2]
CORPUS = Path(__file__).with_name('corpus.json')
OUTPUT = ROOT / 'app/src/main/java/com/paisaplus/compose/messages/MessageModel.kt'

def tokens(text):
    return re.findall(r'[a-z]+', re.sub(r'[0-9]+', ' num ', text.lower()))[:512]


def train():
    rows = json.loads(CORPUS.read_text())
    def fit(training):
        counts = [collections.Counter(), collections.Counter()]
        docs = [0, 0]
        for row in training:
            docs[row['label']] += 1
            counts[row['label']].update(tokens(row['text']))
        vocab = sorted(set(counts[0]) | set(counts[1]))
        totals = [sum(c.values()) + len(vocab) for c in counts]
        weights = {w: math.log((counts[1][w]+1)/totals[1]) - math.log((counts[0][w]+1)/totals[0]) for w in vocab}
        return math.log(docs[1]/docs[0]), weights
    training = [r for r in rows if r['split'] == 'train']
    # Preserve the general-alert expert while adding bank-format vocabulary. Scores are
    # used only after deterministic transaction checks and always require human review.
    experts = [fit([r for r in training if not r.get('bank')]), fit(training)]
    def score(text):
        def expert_score(expert):
            bias, weights = expert
            logit = bias + sum(weights.get(t, 0) for t in tokens(text))
            return 1 / (1 + math.exp(-max(-40, min(40, logit))))
        return max(map(expert_score, experts))
    test = [r for r in rows if r['split'] == 'test']
    threshold = .8
    tp = sum(r['label'] == 1 and score(r['text']) >= threshold for r in test)
    fp = sum(r['label'] == 0 and score(r['text']) >= threshold for r in test)
    fn = sum(r['label'] == 1 and score(r['text']) < threshold for r in test)
    report = dict(model='multinomial-naive-bayes-two-expert-v2', corpus_sha256=hashlib.sha256(CORPUS.read_bytes()).hexdigest(),
                  training_rows=len(training), training_families=len({r['family'] for r in rows if r['split']=='train'}),
                  held_out_rows=len(test), threshold=threshold, true_positives=tp, false_positives=fp, false_negatives=fn,
                  note='Synthetic template-disjoint smoke evaluation; not real-world accuracy or phishing authentication.')
    Path(__file__).with_name('evaluation.json').write_text(json.dumps(report, indent=2)+'\n')
    maps = []
    for name, (bias, weights) in zip(['general', 'bank'], experts):
        entries = ',\n'.join(f'        "{w}" to {v:.10f}' for w,v in weights.items())
        maps.append(f'    private const val {name}Bias = {bias:.10f}\n    private val {name}Weights = mapOf(\n{entries}\n    )\n')
    OUTPUT.write_text('''// Generated by tools/message_model/train.py. Do not edit weights by hand.
package com.paisaplus.compose.messages

import java.util.Locale
import kotlin.math.exp

/** Synthetic-data baseline. Score measures transaction-like text, never sender authenticity. */
object MessageModel {
    const val THRESHOLD = 0.8
    private val words = Regex("[a-z]+")
    private val digits = Regex("[0-9]+")
'''+''.join(maps)+'''
    fun score(text: String): Double {
        val normalized = digits.replace(text.lowercase(Locale.ROOT), " num ")
        val tokens = words.findAll(normalized).take(512).map { it.value }.toList()
        fun expert(bias: Double, weights: Map<String, Double>): Double {
            val logit = bias + tokens.sumOf { weights[it] ?: 0.0 }
            return 1.0 / (1.0 + exp(-logit.coerceIn(-40.0, 40.0)))
        }
        return maxOf(expert(generalBias, generalWeights), expert(bankBias, bankWeights))
    }
}
''')
    print(json.dumps(report, indent=2))

if __name__ == '__main__':
    train()
